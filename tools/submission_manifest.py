"""Build the upload manifest: every file Editorial Manager will ask for, with a checksum.

The point is not documentation, it is that the last step of a submission is a sequence of file pickers, and picking
the wrong version of a table (or forgetting the highlights file) is the most common avoidable failure at that step.
This script lists each slot, the file that fills it, its size and its hash, and refuses to print a green manifest if
a slot is missing or empty.

    python tools/submission_manifest.py
"""
from __future__ import annotations

import hashlib
from pathlib import Path

ROOT = Path(".").resolve()
SUB = ROOT / "submission" / "jvcir"
FIG = ROOT / "figures_j"
OUT = SUB / "UPLOAD_MANIFEST.md"

# (slot, file, required, note)
SLOTS: list[tuple[str, Path, bool, str]] = [
    ("Manuscript (source)", SUB / "main.tex", True, "the .tex is the source file; a PDF alone is not accepted"),
    ("Manuscript (bibliography)", SUB / "refs.bib", True, ""),
    ("Manuscript (PDF for review)", SUB / "main.pdf", True, "generated, not hand-edited"),
    ("Highlights", SUB / "highlights.txt", True, "5 bullets, all <= 85 characters"),
    ("Cover letter (PDF)", SUB / "cover_letter.pdf", True, "typeset form of COVER_LETTER.md"),
    ("Declaration of competing interest", SUB / "declaration_of_competing_interest.docx", True, ""),
    ("Graphical abstract", FIG / "graphical_abstract.pdf", False, "optional; Elsevier encourages it"),
]
for i, stem in enumerate(("fig1_framework", "fig2_frontier", "fig3_audit", "fig4_decibel", "fig5_viewlevel",
                          "fig6_qualitative"), start=1):
    SLOTS.append((f"Figure {i}", FIG / f"{stem}.pdf", True, f"vector; the 300 dpi PNG sits next to it"))
for tab in sorted(SUB.glob("tab_*.tex")):
    SLOTS.append((f"Table source ({tab.stem})", tab, True, "generated; byte-identical on regeneration"))


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:12]


def main() -> int:
    rows, missing = [], []
    for slot, path, required, note in SLOTS:
        ok = path.exists() and path.stat().st_size > 0
        if not ok and required:
            missing.append(f"{slot}: {path.name}")
        rows.append((slot, path, ok, required, note))

    lines = ["# Upload manifest — JVCIR submission", "",
             "Generated by `tools/submission_manifest.py`. Every line is a file picker in Editorial Manager.", "",
             "| slot | file | bytes | sha256 | ok | note |", "|---|---|---|---|---|---|"]
    for slot, path, ok, required, note in rows:
        rel = path.relative_to(ROOT).as_posix() if path.exists() else path.name
        size = f"{path.stat().st_size:,}" if path.exists() else "—"
        digest = sha(path) if ok else "—"
        mark = "yes" if ok else ("**MISSING**" if required else "optional")
        lines.append(f"| {slot} | `{rel}` | {size} | `{digest}` | {mark} | {note} |")

    lines += ["", "## Author actions that no script can do", "",
              "1. Paste the Zenodo DOI into the one remaining `\\TBD{}` slot: `python tools/fill_doi.py --doi ...`.",
              "2. Upload the declaration `.docx` (or paste the same text into Elsevier's declarations tool).", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")

    width = max(len(s) for s, *_ in rows)
    for slot, path, ok, required, note in rows:
        flag = "OK  " if ok else ("MISS" if required else "opt ")
        print(f"  [{flag}] {slot:<{width}}  {path.name}")
    print(f"\n{len(rows)} slots, {len(missing)} missing")
    if missing:
        for m in missing:
            print("  -", m)
        return 1
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
