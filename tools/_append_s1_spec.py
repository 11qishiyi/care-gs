SEC = r"""

## S1 规格：与「已发表格式」的基线在同字节下对撞（预注册 2026-11-14 18:35，数据落盘前）

### S1.0 为什么需要这一节

M1–M13 的对手全是**我们自己的族**（标量阶梯、字典、剪枝）。论文的主张是「等字节下，
改精度胜过改数量」，但读者会问：这条阶梯**比已发表的做法强多少**？没有这一节，
「超越 SOTA」只是一个内部比较。

### S1.1 基线是什么（诚实定义）

把**已发表格式**在本仓库的数据上重新实现，走同一个量化器、同一个渲染器、同一个字节表：

| 名称 | 语法 | 含义 | 模型字节 | 模型倍率 |
|---|---|---|---|---|
| SH 8-bit | `sh8_g32` | 逐块尺度量化 SH，几何保持 fp32（仓库既有 publish 量化器） | 94.00 | 2.51× |
| SH 4-bit | `sh4_g32` | 同上，4 bit | 70.00 | 3.37× |
| prune50 + SH8 | `p50_q8_g32` | 按 Fisher 删 50%，再量化幸存系数 | 94.00 | 5.02× |
| prune50 + SH4 | `p50_q4_g32` | 同上，4 bit | 70.00 | 6.74× |
| prune30 + SH4 | `p30_q4_g32` | 删 70%，再 4 bit | 70.00 | 11.24× |
| prune30 + SH2 | `p30_q2_g32` | 删 70%，再 2 bit | 58.00 | 13.56× |

**这不是任何单篇论文流水线的复现**：我们不训练、不蒸馏、不做 anchor 重参数化，只复现
「保留多少 × 每个系数多少位」这一层。它对应的正是本论文讨论的动作空间，也正是压缩文献
里最常被引用的那一层。任何更强的已发表结果（需要重训练）不在本节的可比范围内，文档中
必须写清这一点。

### S1.2 指标与判据（预注册，不得事后改）

对每个资产、每个基线行 b（其**实测**码率 r_b），在我们的实测点里取「码率 ≤ 1.05·r_b」
的变体中覆盖损失最小者 m，定义

    Δ = drop_pp(m) − drop_pp(b)     （正 = 我们少丢）

**S1（主判据）**：Δ ≥ 1.0 pp **且** 配对区间分离（`m.drop_lo_pp > b.drop_hi_pp`），
对**每一个**基线都成立；满足条件的资产数 ≥ 6/8（`frac = 0.75`）。

**S1b（护栏）**：上述获胜变体的 dPSNR 不得比基线的 dPSNR 差 0.3 dB 以上 —— 允许我们的
覆盖更好，但不允许靠「把图像糊掉」换取覆盖率（M2 已经见过 PSNR 奖励模糊的反例）。

**禁止条款**：不得改 5% 的字节容差、不得改 1.0 pp 门槛、不得剔除资产、不得跨预算比较
（基线在哪个预算就只在那个预算上比）、不得把 `covered=false` 的行拿来比较。

### S1.3 结局

| 结果 | 结论 |
|---|---|
| S1 ✔ 且 S1b ✔ | 可以在论文里写「在同等字节、同一协议、同一资产上，本方法的覆盖损失比已发表格式低 ≥1 pp」 |
| S1 ✔ 但 S1b ✘ | 只能主张覆盖率，保真度为代价，须在文中说明 |
| S1 ✘ | 「超越 SOTA」不成立，只能主张「等字节下改精度优于改数量」，写入负结果附录 |

### S1.4 执行

S1 字节测量（8 资产 × 7 配置，`m4_bytes --skip-flat`，zstd-12）→ 覆盖分析
（`m1_analyse --bytes-json`，400 splits）→ `experiments/sota_report.py` 出表 →
**立即释放节点**。A40 约 1.5 h ≈ ¥4.3。
"""
