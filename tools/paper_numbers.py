"""Generate `experiments/PAPER_NUMBERS.md`: every number the paper will quote, derived from its artifact.

Typed tables drift — that is how "85 % geometry" survived five documents and how a protocol-excluded bonsai row
re-entered a summary. This script rebuilds the tables from the artifact files themselves, so the document either
matches the measurements or the drift test fails.

    python3 tools/paper_numbers.py            # print
    python3 tools/paper_numbers.py --out experiments/PAPER_NUMBERS.md
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "experiments"))

import audit_mseries_tables as AUDIT  # noqa: E402
import gap_report as GAP  # noqa: E402
import protocol_assets as PA  # noqa: E402

ART = ROOT / "experiments/artifacts/a4"


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def mid_rate_rows() -> list[str]:
    """M47 (bicycle seed 1) and M48 (three scenes) log pairs, as measured."""
    out = ["| scene | arm | file | PSNR | source |", "|---|---|---|---|---|"]
    labels = {"enc_v": "volume, 48-bit", "enc_g": "saliency, 48-bit", "enc_g40": "saliency, 40-bit",
              "enc_g32": "saliency, 32-bit", "enc_v_b48": "volume, 48-bit", "enc_g_b48": "saliency, 48-bit",
              "enc_g_b40": "saliency, 40-bit", "enc_g_b32": "saliency, 32-bit"}
    for tag, d in (("bicycle seed 1", ART / "m47"),
                   ("bicycle seed 2", ART / "fetch/bicycle_s2"),
                   ("stump", ART / "fetch/stump_s0"),
                   ("bonsai (internal only)", ART / "fetch/bonsai_s0")):
        for row in AUDIT.pairs_from_logs(d):
            stem = row["raw"].split(":")[0]
            arm = labels.get(stem, stem)
            out.append(f"| {tag} | {arm} | {row['mb']} MB | {row['psnr']:.2f} | `{d.relative_to(ROOT)}` |")
    return out


def near_lossless_rows() -> list[str]:
    out = ["| scene | spec | file | PSNR | SSIM | decode | source |", "|---|---|---|---|---|---|---|"]
    rows = AUDIT.read_rows(ART / "m51/rows_final.txt")
    for r in rows:
        p = r["raw"].split()
        scene, spec, nbytes, psnr, ssim, wall, rss = p[0], p[1], int(p[2]), float(p[3]), p[4], p[5], int(p[6])
        out.append(f"| {scene} | `{spec}` | {nbytes:,} B ({nbytes / 1e6:.2f} MB) | {psnr:.2f} | {float(ssim):.4f} | "
                   f"{wall} s / {rss / 1e6:.2f} GB | `artifacts/a4/m51` |")
    return out


def colour_budget_rows() -> list[str]:
    out = ["| colour bits | file | PSNR | source |", "|---|---|---|---|"]
    for line in _read(ART / "m49/bytes.txt").splitlines():
        bits, nbytes = line.split()
        log = ART / f"m49/render_m49g_b{bits}_f1.log"
        m = re.search(r"PSNR=\s*([0-9.]+)", _read(log))
        if m:
            out.append(f"| {bits} | {int(nbytes):,} B ({int(nbytes) / 1e6:.2f} MB) | {float(m.group(1)):.2f} | `artifacts/a4/m49` |")
    m = re.search(r"PSNR=\s*([0-9.]+)", _read(ART / "m49/render_m49raw_g_f1.log"))
    if m:
        out.append(f"| raw (no container) | 236 B/prim | {float(m.group(1)):.2f} | `artifacts/a4/m49` |")
    return out


def geometry_rows() -> list[str]:
    out = ["| spec | file | PSNR | Δ bytes vs control | Δ dB |", "|---|---|---|---|---|"]
    rows = AUDIT.read_rows(ART / "m50/rows.txt")
    if not rows:
        return out
    base_bytes, base_psnr = rows[0]["bytes"], rows[0]["psnr"]
    for r in rows:
        spec = r["raw"].split()[0]
        dbytes = 100.0 * (r["bytes"] - base_bytes) / base_bytes
        out.append(f"| `{spec}` | {r['bytes']:,} B ({r['bytes'] / 1e6:.2f} MB) | {r['psnr']:.2f} | "
                   f"{dbytes:+.2f} % | {r['psnr'] - base_psnr:+.2f} |")
    return out


def stream_rows() -> list[str]:
    out = ["| stream | MB | B/primitive |", "|---|---|---|"]
    txt = _read(ART / "m24_encode_streams.txt")
    total = None
    for line in txt.splitlines():
        m = re.match(r"\s+(\w+)\s+([0-9.]+)/\s*([0-9.]+)", line)
        if m and m.group(1) not in ("stream",):
            out.append(f"| {m.group(1)} | {float(m.group(3)):.2f} | {float(m.group(3)) * 1e6 / 6131954:.2f} |")
        m2 = re.search(r"auto\s+([0-9.]+) MB", line)
        if m2:
            total = m2.group(1)
    if total:
        out.append(f"| **total** | {float(total):.2f} | {float(total) * 1e6 / 6131954:.2f} |")
    return out


def build() -> str:
    gap = GAP.build_report()
    gap_md = GAP.render_md(gap).splitlines()
    gap_table = [ln for ln in gap_md if ln.startswith("|")]
    lines = [
        "# PAPER_NUMBERS — every number the paper quotes, derived from its artifact",
        "",
        "Generated by `tools/paper_numbers.py`; `experiments/tests/test_paper_numbers.py` fails if this file and the",
        "artifacts disagree. Do not edit by hand.",
        "",
        "## 0. Which scenes may be compared across papers",
        "",
        "| scene | cross-paper | our clean | published 3DGS | why |",
        "|---|---|---|---|---|",
    ]
    for scene, v in PA.ASSETS.items():
        lines.append(f"| {scene} | {'yes' if v['cross_paper'] else '**no**'} | {v['clean_ours']:.2f} | "
                     f"{v['clean_published_3dgs']:.2f} | {v['why']} |")
    lines += ["", "## 1. Gap to the published frontier (computed, not narrated)", ""] + gap_table
    lines += ["", "## 2. Mid-rate: the saliency prune against the volume score (M47/M48)", ""] + mid_rate_rows()
    lines += ["", "## 3. Near-lossless shipping rows and the opacity knob (M51)", ""] + near_lossless_rows()
    lines += ["", "## 4. Colour budget on one model (M49)", ""] + colour_budget_rows()
    lines += ["", "## 5. Geometry precision, one field at a time (M50)", ""] + geometry_rows()
    lines += ["", "## 6. Where the bytes are (M24 stream attribution, gp8-6-6_c9)", ""] + stream_rows()
    lines += ["", "## 7. Audit status", "",
              "| round | rows checked | tool |", "|---|---|---|",
              "| M47 | 3 | `audit_mseries_tables.audit_logs_case` |",
              "| M48 | 10 | same |",
              "| M49–M51 | 19 | `audit_mseries_tables.audit_case` |",
              "",
              "M1–M46 are still self-attested per round; extending the audit backwards is a background task.", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out")
    a = ap.parse_args()
    text = build()
    if a.out:
        (ROOT / a.out).write_text(text, encoding="utf-8")
        print(f"wrote {a.out} ({len(text)} B)")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
