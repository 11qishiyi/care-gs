SEC = """

## N22 判据的天花板：要求「赢 1 pp」而对手已经丢 0.00

**做了什么**：S1 把已发表格式的基线在本仓库 8 个资产上重新实现（`sh8_g32`、`sh4_g32`、
`p50_q8_g32`、`p50_q4_g32`、`p30_q4_g32`、`p30_q2_g32`），在同一量化器、同一渲染器、同一
实测字节表下与我们自己的阶梯逐资产对撞。预注册判据是「每个基线都被至少 1.0 pp 赢掉，
且配对区间分离」。

**结果**：S1 **FAIL 0/8**。原因不是我们差，而是**前两列基线自身的损失已经是 0.00 / −0.02 pp**：
覆盖损失的上界是 0，任何方法都不可能「在 0.00 上再赢 1 pp」。8 个资产 × 2 列 = 16 个配对
按定义必败；余下 4 列（prune + quantise，5.5–17×）全部通过。

**事后探索（明确标为事后）**：只保留自身损失 ≤ −1.0 pp（有 1 pp 以上可赢空间）的基线，
S1′ = **8/8 资产、32/32 配对全胜**，Δ 中位 **+8.78 pp**、最小 **+2.87 pp**，
且 dPSNR 比基线好 **0.12–5.60 dB**。

**教训**：
- **N13 的同一条教训在一个项目里复发了第二次**：写判据时必须先问「基线的数值离上界有多远」。
  要求「赢 X」而对手已经贴着 0，等价于要求超过物理上界。正确写法是二选一：
  要么写成**绝对阈值**（「我们 ≤1.0 pp」），要么在判据里显式声明**对手必须有头部空间**。
- **判据的失败可以是信息**，但必须与结果分开陈述：S1 FAIL 是在说判据错，S1′ 的 8/8 是在说
  方法对。把两者混成一句「S1 通过」就是造假；把 S1′ 当成预注册结果也是造假。
- **补上基线才发现前沿读数错了**：M1–M13 的网格里从来没有「只量化 SH、几何保持 fp32」这一行，
  于是 M13 把 3× 的损失报成 −0.39 pp；补测后同一预算是 **+0.00 pp**，零损失货架从 10.6× 前移到
  **2.05–2.83×**。**自建阶梯必须包含「最简单的那一行」**，否则前沿的下端是虚构的。

**收束**：S1 的实质结论是——**在 5.5× 及以上，已发表格式（删基元 + 量化）比我们多丢 2.9–20.9 pp；
在 2.8× 以下，它已经零损失，任何方法都无法在此区间赢它**。论文里能写的是前一句，
不能写的是「我们全面优于已发表方法」。
"""
