import argparse
import json
import os
import shutil
import sys
import time
import zipfile

D = "submission/cviu/deposit"

CODE = [
    "experiments/common.py",
    "experiments/audit_bound.py",
    "experiments/dump_artifacts.py",
    "experiments/make_pup_variant.py",
    "experiments/region_coverage.py",
    "experiments/extend_eval.py",
    "experiments/build_archive.py",
    "experiments/prep_aliases.py",
    "experiments/fetch_hf_curl.sh",
    "experiments/run_cviu.sh",
    "experiments/run_selftrain_audit.sh",
    "repro/run_all.sh",
    "tools/cviu_audit_tables.py",
    "tools/verify_cviu.py",
    "tools/cviu_gate.py",
    "tools/cviu_compliance.py",
    "tools/fill_cviu_tbds.py",
    "tools/make_deposit.py",
]

DATA = [
    "results_v120/audit_bound.json",
    "results_v120/dump_summary.json",
    "submission/cviu/tab_audit.tex",
    "submission/cviu/tab_kview.tex",
    "submission/cviu/tab_fidelity.tex",
    "submission/cviu/highlights.txt",
]

README = """# Deposit: coverage certificates for edited 3D Gaussian Splatting assets

This record accompanies the manuscript *Valid but Unusable, and Auditable: Coverage
Certificates for 3D Gaussian Splatting Assets Under Editing* (submitted to Computer Vision
and Image Understanding).

## What is here

| path | what it is |
|---|---|
| `data/audit_bound.json` | the audit and envelope measurement, one row per asset x edit (63 cells), including the per-split error distribution and the k-view curve |
| `data/dump_summary.json` | PSNR and SSIM per variant per view for the 9 scene-checkpoints |
| `tables/` | the three LaTeX tables exactly as they appear in the manuscript, generated from the JSON above |
| `code/` | every script needed to go from the public archive to those numbers |
| `REPRODUCE.md` | the command sequence, hardware, wall-clock and cost |

## What is NOT here, and why

* **The per-view residual dumps** (`*.npz`, about 40 MB per scene-checkpoint, 9 in total).
  They are the direct input to `code/experiments/audit_bound.py` and they are large. They
  can be regenerated from the public archive in one GPU pass (`code/experiments/run_cviu.sh
  dump`, about 40 minutes on one V100); the exact command is in `REPRODUCE.md`. If the
  reviewers want the dumps themselves, they are available from the author on request and can
  be added to this record.
* **The 3DGS checkpoints we trained ourselves** (barcelona, bilbao, chicago): they are
  regenerated by `code/experiments/run_selftrain_audit.sh` from the public BungeeNeRF
  capture, and the three released assets come from the public archive named in the paper.

## Reproduction in one paragraph

Download the public 3DGS output archive, run the data stage, then the dump stage (GPU), then
the audit stage (CPU). The four published 30%-prune degradations must come out as 22.1, 10.8,
27.7 and 15.2 points; `code/tools/cviu_gate.py` asserts exactly that and exits non-zero
otherwise. `code/tools/verify_cviu.py` then re-derives every number in the manuscript from
these JSON files.

## Licence

Code: MIT. Data and tables: CC BY 4.0. Please confirm both before publishing this record.
"""

REPRO = """# Reproduce

Hardware used: one NVIDIA V100-SXM2-16GB, 64 GB RAM, 200 GB disk, Ubuntu 22.04,
Python 3.12, torch 2.6.0+cu121, gsplat 1.5.3, scikit-image 0.26.

Wall clock on that machine: data stage ~50 min (9.6 GB download + extraction), dump stage
~40 min, audit stage ~2 h (CPU, 400 splits x 8 variants x 9 checkpoints). Rental cost at the
time: 1.85 CNY/h, about 6.7 CNY for the whole campaign.

```bash
# 0. one public archive plus one public HF mirror; no private data
bash repro/run_all.sh data          # -> /workspace/data/out3dgs/output/<scene>/...

# 1. GPU: 9 scene-checkpoints x 8 variants, residual dumps + PSNR/SSIM
bash experiments/run_cviu.sh dump   # -> /workspace/res/rev/dump/<scene>.npz

# 2. CPU: the audit, the Kolmogorov envelope, the k-view curve
bash experiments/run_cviu.sh audit  # -> /workspace/res/cviu/audit_bound.json

# 3. the gate: the four published degradations must reproduce to 0.1 points
python tools/cviu_gate.py

# 4. regenerate the manuscript tables and check the manuscript against them
python tools/cviu_audit_tables.py --dump /workspace/res/rev/dump \\
    --audit /workspace/res/cviu/audit_bound.json --out-dir submission/cviu
python tools/verify_cviu.py
```

Two pitfalls that cost us a run each:

* `download.pytorch.org` is throttled to a few kB/s on some cloud nodes, so LPIPS cannot
  fetch its AlexNet backbone. The paper therefore reports PSNR and SSIM only; the dump stage
  skips LPIPS loudly rather than hanging.
* `matcli node exec` needs the whole command as one `--command` string, and long jobs must be
  started with `nohup ... &`, or the session times out before the job finishes.
"""


def build():
    if os.path.exists(D):
        shutil.rmtree(D)
    for sub in ("code", "data", "tables"):
        os.makedirs(os.path.join(D, sub), exist_ok=True)

    n = 0
    for rel in CODE:
        if not os.path.exists(rel):
            print("  skip (missing):", rel)
            continue
        dst = os.path.join(D, "code", rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(rel, dst)
        n += 1
    for rel in DATA:
        if not os.path.exists(rel):
            print("  skip (missing):", rel)
            continue
        base = os.path.basename(rel)
        sub = "tables" if base.endswith(".tex") or base.endswith(".txt") else "data"
        shutil.copy2(rel, os.path.join(D, sub, base))
        n += 1

    open(os.path.join(D, "README.md"), "w", encoding="utf-8").write(README)
    open(os.path.join(D, "REPRODUCE.md"), "w", encoding="utf-8").write(REPRO)
    open(os.path.join(D, "LICENSE"), "w", encoding="utf-8").write(
        "Code: MIT License\nData and tables: CC BY 4.0\nCopyright (c) 2026 Tianji Su\n")

    audit = "results_v120/audit_bound.json"
    prov = dict(
        generated=time.strftime("%Y-%m-%dT%H:%M:%S"),
        campaign=dict(node="2138563", gpu="NVIDIA Tesla V100-SXM2-16GB",
                      driver="550.127.08", torch="2.6.0+cu121", gsplat="1.5.3",
                      cost_cny=6.7),
        scene_checkpoints=9, edits=7, cells=63, splits=400, alpha=0.10,
        gate="bicycle 22.1 / flowers 10.8 / stump 27.7 / treehill 15.2, |d| <= 0.1",
    )
    if os.path.exists(audit):
        a = json.load(open(audit, encoding="utf-8"))
        prov["summary"] = a.get("summary", {})
    open(os.path.join(D, "PROVENANCE.json"), "w", encoding="utf-8").write(
        json.dumps(prov, indent=2, ensure_ascii=False))

    zp = "submission/cviu/deposit.zip"
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(D):
            for f in sorted(files):
                p = os.path.join(root, f)
                z.write(p, os.path.relpath(p, os.path.dirname(D)))
    print(f"built {D}: {n} files copied; zip {zp} "
          f"({os.path.getsize(zp) / 1024:.0f} kB)")
    return 0


def check():
    must = ["README.md", "REPRODUCE.md", "PROVENANCE.json", "LICENSE",
            "data/audit_bound.json", "data/dump_summary.json",
            "tables/tab_audit.tex", "code/experiments/audit_bound.py",
            "code/tools/verify_cviu.py"]
    ok = True
    for m in must:
        p = os.path.join(D, m)
        good = os.path.exists(p) and os.path.getsize(p) > 0
        print(f"{'OK ' if good else 'MISSING'} {m}")
        ok &= good
    zp = "submission/cviu/deposit.zip"
    if os.path.exists(zp):
        with zipfile.ZipFile(zp) as z:
            bad = z.testzip()
            print(f"zip {len(z.namelist())} entries, integrity {'OK' if bad is None else bad}")
            ok &= bad is None
    return 0 if ok else 1


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sys.exit(check() if a.check else build())
