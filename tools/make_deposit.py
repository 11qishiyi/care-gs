"""Assemble the deposit bundle for the Data availability statement.

The bundle is what makes the paper's claims checkable by someone who has none of our
machines: the measured JSON, the code that produced it, the verification suite, and a
README that states the hardware, the cost and the two things that are *not* included.

    python tools/make_deposit.py            # build submission/cviu/deposit/ + .zip
    python tools/make_deposit.py --check    # verify an existing bundle

The per-view residual dumps (``*.npz``, ~40 MB per scene-checkpoint) are deliberately
**not** bundled by this script: they live on the rental node and are fetched separately.
The README says so, because a deposit that silently omits its own input is worse than one
that names the omission.
"""
