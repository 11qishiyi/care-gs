#!/usr/bin/env bash
# M35 -- the rate-distortion map, the M34 robustness debt, and a model cache that outlives the node.
# stages: setup <scene> | models | ladder <scene> | render <scene> | damage <scene> | cache | all <scene>
set -euo pipefail
ROOT=/workspace/code
OUT=/workspace/res/m35
ARCH=/workspace/data/m360std
COLMAP=/workspace/data/mip360_colmap
DATA=/workspace/data
CACHE=/mnt/m35cache
ZIP=https://repo-sam.inria.fr/fungraph/3d-gaussian-splatting/datasets/pretrained/models.zip
SCENE="${2:-bicycle}"
export PYTHONPATH="$ROOT/research/code:$ROOT:$ROOT/experiments"
PY=python3
mkdir -p "$OUT" "$CACHE"
log() { echo "[$(date +%H:%M:%S)] $*" | tee -a "$OUT/m35_$SCENE.log"; }
#: `m20_setup.sh` writes the published model here; the M31 layout under `$DATA/models/...` is only
#: populated when a round starts from `run_m17.sh data`.  Accept either, prefer what exists.
PLY="$DATA/m20/$SCENE.ply"
[ -s "$PLY" ] || PLY="$DATA/models/output/$SCENE/point_cloud/iteration_30000/point_cloud.ply"
MODELS="$DATA/models/output/$SCENE/point_cloud/iteration_30000/point_cloud.ply"

#: The pre-registered ladder (tools/m35_spec.md).  Order matters: the last two change SH degree.
LADDER="gp6-6-6_c8_sh3 gp5-5-5_c7_sh3 gp5-5-5_c6_sh3 gp4-4-4_c6_sh3 gp4-4-4_c6_sh2 gp6-6-6_c6_sh2"

#: every ladder point builds at rank 16 / 48-bit colour, which is what the shipping container uses.
#: `--plans` is COMMA separated (m24_alpha splits on "," and then on ":"), not space separated --
#: passing spaces makes the whole list one item and `int("gp6-6-6_c8_sh3")` raises.  Written out
#: literally rather than generated by printf: the generated form went through two quoting layers
#: (PowerShell -> bash) and silently produced a space-separated string twice.
PLANS="${M35_PLANS:-gp6-6-6_c8_sh3:16:48,gp5-5-5_c7_sh3:16:48,gp5-5-5_c6_sh3:16:48,gp4-4-4_c6_sh3:16:48,gp4-4-4_c6_sh2:16:48,gp6-6-6_c6_sh2:16:48}"
tag() { echo "${1//-/_}"; }

case "${1:-all}" in
  setup)
    bash "$ROOT/experiments/run_m17.sh" deps 2>&1 | tail -1
    SCENES="$SCENE" bash "$ROOT/experiments/m20_setup.sh" 2>&1 | tail -1
    SCENES="$SCENE" bash "$ROOT/experiments/run_m17.sh" data 2>&1 | tail -1
    SCENES="$SCENE" bash "$ROOT/experiments/run_m17.sh" base 2>&1 | tail -3
    bash "$0" models "$SCENE"
    ;;
  models)
    #: Cache first, download only what is missing.  /mnt is the persistent netdisk and is mounted
    #: read-write on this node, so a later round can skip the download entirely.
    #:
    #: The source is hf-mirror with a plain whole-file GET, NOT the INRIA zip by range request.
    #: Measured this round: hf-mirror whole-file 1.52 GB in ~150 s (~10 MB/s), INRIA zip with 12
    #: range workers 0.2 MB/s.  M34's `zip_entry.py` was the right tool for a host that throttles
    #: per connection; this host does not, and a Range request against hf-mirror returns almost
    #: nothing, which is what made `m35_race.sh` report 0.6 kB/s for a link that does 10 MB/s.
    HF=${MIRROR:-https://hf-mirror.com}/datasets/dylanebert/3dgs/resolve/main
    for s in bicycle stump bonsai; do
      if [ -s "$CACHE/$s.ply" ]; then log "cached $s $(stat -c %s "$CACHE/$s.ply") B"; continue; fi
      log "fetch $s from hf-mirror"
      curl -sSL --retry 5 --retry-delay 3 -o "$CACHE/$s.ply.part" \
        "$HF/$s/point_cloud/iteration_30000/point_cloud.ply" && mv "$CACHE/$s.ply.part" "$CACHE/$s.ply"
      log "got $s $(stat -c %s "$CACHE/$s.ply") B"
    done
    mkdir -p "$(dirname "$MODELS")"
    [ -s "$MODELS" ] || ln -sf "$CACHE/$SCENE.ply" "$MODELS"
    ls -l "$CACHE" | tee "$OUT/cache_ls.txt"
    ;;
  ladder)
    log "ladder $SCENE: $LADDER"
    t0=$(date +%s)
    "$PY" -u $ROOT/experiments/m24_alpha.py --ply "$PLY" --plans "$PLANS" \
      --out "$OUT/$SCENE" --no-ply --no-legacy >> "$OUT/build_$SCENE.log" 2>&1
    t1=$(date +%s)
    echo "encode_wall $((t1-t0)) s" | tee "$OUT/enc_$SCENE.txt"
    ls -l "$OUT/$SCENE"/*.gs1 | tee "$OUT/sizes_$SCENE.txt"
    ;;
  render)
    for s in $LADDER; do
      f="$OUT/$SCENE/$(tag "$s")_r16_b048_auto.gs1"
      [ -s "$f" ] || { log "missing $f"; continue; }
      ply="$OUT/$SCENE/$(tag "$s").ply"
      t0=$(date +%s)
      "$PY" -u $ROOT/experiments/m19_codec.py --to-ply "$f" --out "$ply" >> "$OUT/decode_$SCENE.log" 2>&1
      "$PY" $ROOT/experiments/make_m360_archive.py --scene-dir "$COLMAP/$SCENE" --ply "$ply" \
        --archive "$ARCH" --name "${SCENE}_$(tag "$s")" 2>&1 | tail -1
      r=$(bash "$ROOT/experiments/probe_render.sh" "${SCENE}_$(tag "$s")" 1 2>&1 | tail -1)
      t1=$(date +%s)
      echo "$s $(stat -c %s "$f") $((t1-t0))s $r" | tee -a "$OUT/render_$SCENE.log"
      rm -f "$ply"
    done
    ;;
  damage)
    #: M34's P3: the same scene, the same single burst, two frame sizes.  Build both containers here
    #: so the comparison is one run on one node.
    for nf in 4194304 262144; do
      "$PY" -u $ROOT/experiments/m24_alpha.py --ply "$PLY" --plans "gp6-6-6_c8_sh3:16:48" \
        --out "$OUT/${SCENE}_f$nf" --no-ply --no-legacy --min-frame "$nf" \
        --suffix "_f$nf" >> "$OUT/build_${SCENE}_f$nf.log" 2>&1
      f=$(ls "$OUT/${SCENE}_f$nf"/*.gs1 | head -1)
      log "built $f $(stat -c %s "$f") B"
      "$PY" -u "$ROOT/tools/m33_damage.py" --gs1 "$f" --scene-dir "$COLMAP/$SCENE" \
        --archive "$ARCH" --out "$OUT/${SCENE}_f$nf" --tag "${SCENE}_f$nf" --render \
        --burst 0.10,1.0 2>&1 \
        | tail -6 | tee -a "$OUT/damage_${SCENE}_f$nf.log"
    done
    ;;
  cache)
    "$PY" - "$CACHE" "$OUT/m35_cache.json" <<'PY' 2>&1 | tee "$OUT/cache_report.txt"
import hashlib, json, os, sys
cache, out = sys.argv[1], sys.argv[2]
rows = []
for name in ("bicycle", "stump", "bonsai"):
    p = os.path.join(cache, name + ".ply")
    if not os.path.getsize(p) if os.path.exists(p) else True:
        rows.append({"scene": name, "present": False}); continue
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 24), b""):
            h.update(chunk)
    rows.append({"scene": name, "present": True, "bytes": os.path.getsize(p), "sha256": h.hexdigest()})
    print(f"{name:8s} {os.path.getsize(p)/1e6:9.2f} MB  {h.hexdigest()[:16]}")
json.dump({"cache": cache, "files": rows}, open(out, "w"), indent=1)
print("wrote", out)
PY
    ;;
  all) bash "$0" ladder "$SCENE"; bash "$0" render "$SCENE" ;;
  *) echo "use setup|models|ladder|render|damage|cache|all <scene>" >&2; exit 2 ;;
esac
